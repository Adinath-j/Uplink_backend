package com.example.Uplink_Backend.modules.qa.dto;

public class AnswerResponseDto {

    private String id;
    private String questionId;
    private String authorId;
    private String authorName;
    private String authorRole;
    private String authorAvatar;
    private String content;
    private String createdAt;
    private int helpfulCount;
    private boolean isAccepted;
    private boolean hasUserMarkedHelpful;

    public AnswerResponseDto() {}

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getQuestionId() {
        return questionId;
    }

    public void setQuestionId(String questionId) {
        this.questionId = questionId;
    }

    public String getAuthorId() {
        return authorId;
    }

    public void setAuthorId(String authorId) {
        this.authorId = authorId;
    }

    public String getAuthorName() {
        return authorName;
    }

    public void setAuthorName(String authorName) {
        this.authorName = authorName;
    }

    public String getAuthorRole() {
        return authorRole;
    }

    public void setAuthorRole(String authorRole) {
        this.authorRole = authorRole;
    }

    public String getAuthorAvatar() {
        return authorAvatar;
    }

    public void setAuthorAvatar(String authorAvatar) {
        this.authorAvatar = authorAvatar;
    }

    public String getContent() {
        return content;
    }

    public void setContent(String content) {
        this.content = content;
    }

    public String getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(String createdAt) {
        this.createdAt = createdAt;
    }

    public int getHelpfulCount() {
        return helpfulCount;
    }

    public void setHelpfulCount(int helpfulCount) {
        this.helpfulCount = helpfulCount;
    }

    public boolean isAccepted() {
        return isAccepted;
    }

    public void setAccepted(boolean accepted) {
        isAccepted = accepted;
    }

    public boolean isHasUserMarkedHelpful() {
        return hasUserMarkedHelpful;
    }

    public void setHasUserMarkedHelpful(boolean hasUserMarkedHelpful) {
        this.hasUserMarkedHelpful = hasUserMarkedHelpful;
    }
}

